"""Build the LaTeX tables from the frozen model outputs."""

import json
from pathlib import Path

import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results" / "cross_country"
COUNTRIES = {"GBR": "United Kingdom", "USA": "United States", "CHN": "China", "IND": "India"}
MODELS = ["persistence", "shipment", "brent", "full"]


def table(caption, headings, rows):
    align = "l" + "r" * (len(headings) - 1)
    lines = [r"\begin{table}[htbp]", r"\centering", r"\small", rf"\caption{{{caption}}}",
             rf"\begin{{tabular}}{{@{{}}{align}@{{}}}}", r"\toprule", " & ".join(headings) + r" \\",
             r"\midrule"]
    lines.extend(" & ".join(row) + r" \\" for row in rows)
    return "\n".join(lines + [r"\bottomrule", r"\end{tabular}", r"\end{table}"])


def main():
    sample = json.loads((OUT / "sample.json").read_text(encoding="utf-8"))
    panel = pd.read_csv(OUT / "monthly_panel.csv", parse_dates=["month"]).set_index("month")
    metrics = pd.read_csv(OUT / "holdout_metrics.csv").set_index(["mode", "country", "model"])
    sensitivity = pd.read_csv(OUT / "sensitivity.csv").set_index(["country", "specification"])
    correlations = pd.read_csv(OUT / "change_correlations.csv", index_col=0)
    scenario = pd.read_csv(OUT / "scenario.csv").query("month == 2").set_index("country")

    pre = panel.loc[:"2026-02-01", "hormuz_index"].mean()
    post = panel.loc["2026-05-01":, "hormuz_index"].mean()
    first, fit_start = [pd.Timestamp(sample[key]).strftime("%B %Y") for key in ("panel_start", "fit_start")]
    summary = (
        f"The main panel has {sample['panel_months']} aligned months from {first} to August 2026. "
        f"The common fitting window begins in {fit_start} and contains "
        f"{sample['training_transitions']} transitions through April 2026. "
        f"May--August 2026 supplies {sample['holdout_transitions']} holdout transitions per country. "
        f"The mean observed shipment index was {pre:.2f} before March 2026 in the aligned panel "
        f"and {post:.2f} during the holdout. In the fitted months the correlation between "
        f"the lagged shortfall and log Brent was {sample['train_shortfall_brent_log_r']:.2f}."
    )
    pieces = [r"% Generated by src/report_tables.py.", summary]
    for mode, caption in [
        ("one_step", "One-step holdout errors in USD/t. Each cell shows MAE / RMSE."),
        ("recursive", "Recursive holdout errors in USD/t. Each cell shows MAE / RMSE."),
    ]:
        rows = []
        for code, country in COUNTRIES.items():
            cells = []
            for model in MODELS:
                entry = metrics.loc[mode, code, model]
                cells.append(f"{entry.mae_usd_t:.1f} / {entry.rmse_usd_t:.1f}")
            rows.append([country, *cells])
        pieces.append(table(caption, ["Country", "Persistence", "Shipments", "Brent", "Both"], rows))

    rows = [[country, f"{correlations.loc[f'log_{code}', 'shortfall']:.2f}",
             f"{correlations.loc[f'log_{code}', 'log_brent']:.2f}"]
            for code, country in COUNTRIES.items()]
    pieces.append(table("Exploratory correlations of monthly log unit-value changes with input changes. "
                        "The calculation uses the aligned panel, including the holdout.",
                        ["Country", "Lagged shortfall", "Log Brent"], rows))

    rows = []
    for code, country in COUNTRIES.items():
        cells = [f"{sensitivity.loc[code, variant].pct_for_10_index_points:+.2f}"
                 for variant in ("lag_0", "main", "lag_2", "pre_disruption")]
        rows.append([country, f"{sensitivity.loc[code, 'main'].tau_months:.2f}", *cells])
    pieces.append(table(
        r"Fitted time constant and long-run conditional difference (\%) for a 10-point index shortfall. "
        r"The pre-disruption column uses one-month lag and training through February 2026.",
        ["Country", r"$\tau$ (months)", "No lag", "One month", "Two months", "Pre-disruption"], rows))

    rows = []
    for code, country in COUNTRIES.items():
        values = scenario.loc[code]
        rows.append([country, *(f"{values[f'gap_p{q}_pct']:+.2f}" for q in ("05", "50", "95"))])
    pieces.append(table(
        r"Simulated month-2 percentage difference from the paired reference at fixed Brent. "
        r"These pointwise percentiles describe scenario variation at fixed fitted parameters.",
        ["Country", "5th percentile", "Median", "95th percentile"], rows))
    (ROOT / "report" / "results.tex").write_text("\n\n".join(pieces) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
