"""Build the five-year report's evidence tables."""

import json
from pathlib import Path

import pandas as pd

from report_tables import COUNTRIES, table


ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results" / "five_year"


def main():
    sample = json.loads((OUT / "sample.json").read_text(encoding="utf-8"))
    regime = pd.read_csv(OUT / "regime_means.csv")
    errors = pd.read_csv(OUT / "holdout_metrics.csv").set_index(["proxy", "mode", "country", "model"])
    windows = pd.read_csv(OUT / "holdout_mae_by_regime.csv").set_index(["proxy", "period", "country", "model"])
    physical = pd.read_csv(OUT / "physical_flow_crosscheck.csv").set_index("period")

    summary = (
        f"The five-year panel contains {sample['panel_months']} monthly observations for each of four countries "
        f"({sample['price_observations']} national unit values). The first month supplies the initial price. "
        f"The fit uses {sample['training_transitions']} transitions through December 2024 and "
        f"the holdout contains {sample['holdout_transitions']} transitions from January 2025 through June 2026. "
        f"For China, Comtrade and GACC overlap for {sample['china_source_overlap_months']} months. "
        f"The median absolute difference between their monthly unit values is "
        f"{sample['china_overlap_median_absolute_difference_pct']:.2f}\\%. "
        f"The tanker cargo index correlates {sample['volume_vs_crude_r_2025']:.2f} with the WTO outbound "
        f"crude index in 2025 and {sample['volume_vs_crude_r_full_overlap']:.2f} over January 2025--June 2026."
    )
    pieces = [r"% Generated by src/five_year_tables.py.", summary]

    rows = [[row.regime, str(row.months), f"{row.tanker_volume_index:.1f}", f"{row.brent_usd_bbl:.1f}"]
            for row in regime.itertuples(index=False)]
    pieces.append(table("Phase means for the tanker cargo index and Brent. The 2024 daily activity mean is 100.",
                        ["Observation phase", "Months", "Tanker cargo index", "Brent (USD/bbl)"], rows))

    rows = []
    for code, label in COUNTRIES.items():
        cells = [f"{errors.loc['volume', 'one_step', code, model].mae_usd_t:.1f}"
                 for model in ("persistence", "shipment", "brent", "full")]
        cells.append(f"{errors.loc['count', 'one_step', code, 'full'].mae_usd_t:.1f}")
        rows.append([label, *cells])
    pieces.append(table(
        "Five-year analysis, one-step holdout MAE (USD/t) over January 2025--June 2026. "
        "The last column replaces the cargo index with a tanker count index.",
        ["Country", "Persistence", "Cargo", "Brent", "Brent + cargo", "Brent + count"], rows))

    rows = []
    for code, label in COUNTRIES.items():
        cells = []
        for phase in ("2025", "Mar to Jun 2026"):
            for model in ("brent", "full"):
                cells.append(f"{windows.loc['volume', phase, code, model].absolute_error_usd_t:.1f}")
        rows.append([label, *cells])
    pieces.append(table(
        "One-step holdout MAE (USD/t) for all of 2025 (12 months) and March--June 2026 (4 months).",
        ["Country", "2025 Brent", "2025 both", "2026 Brent", "2026 both"], rows))

    rows = [[period, f"{physical.loc[period].crude_condensate_million_bbl_per_day:.1f}",
             f"{physical.loc[period].tanker_volume_index:.1f}", f"{physical.loc[period].tanker_count_index:.1f}"]
            for period in physical.index]
    pieces.append(table("Physical flow estimates and tanker activity indices. The EIA volumes retain their original annual or quarterly resolution.",
                        ["Period", "EIA (million b/d)", "Tanker cargo index", "Tanker count index"], rows))

    (ROOT / "report" / "five_year_results.tex").write_text("\n\n".join(pieces) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
